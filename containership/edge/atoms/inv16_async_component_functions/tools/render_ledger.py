def main():
    rows = ["| # | Component | Pri | Status | Evidence | Notes |", "|---|---|---|---|---|---|"]
    for n, t, p, s, ev, note in cs.ITEMS:
        rows.append(f"| {n} | {t} | {p} | **{s}** | {'<br>'.join(f'`{e}`' for e in ev)} | {note} |")
    counts = {s: sum(1 for i in cs.ITEMS if i[3] == s) for s in ("PASS", "PARTIAL", "BLOCKED", "OPEN")}
    p0 = [i for i in cs.ITEMS if i[2] == "P0" and i[3] != "PASS"]
