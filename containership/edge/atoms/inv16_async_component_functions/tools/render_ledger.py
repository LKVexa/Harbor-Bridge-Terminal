        f"Owner: {cs.OWNER} · Target version: {cs.TARGET} · Waivers: none issued · "
        "Generated by `tools/render_ledger.py`.",
        "Evidence paths are relative to `evidence/` unless they name a repository file.", "",
        "**Totals:** " + " · ".join(f"{k} {v}" for k, v in counts.items()),
        "", f"**Production certification:** NO_GO — {len(p0)} P0 items are not PASS: "
        + ", ".join(f"#{i[0]}" for i in p0) + ".", "", *rows, "",
        "## Final production-exit checklist", "", "| Exit criterion | State |", "|---|---|",
        *[f"| {a} | {b} |" for a, b in EXIT], "",
        "## What unblocks certification (owner / sibling inputs)", "",
        "1. Supply and pin `pk_core` (version + hash) → items 1, 41, and the 100-item gate.",
