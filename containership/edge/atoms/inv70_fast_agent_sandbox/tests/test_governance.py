class RTM(unittest.TestCase):
    def test_covers_all_100_and_every_remediated_row_is_traceable(self):
        rtm = yaml.safe_load((ROOT / "requirements/RTM.yaml").read_text())
        ids = [r["id"] for r in rtm["rows"]]
        self.assertEqual(len(ids), 100)
        self.assertEqual(len(set(ids)), 100)
        by = {r["id"]: r for r in rtm["rows"]}
        for cid, (st, impl, tests, gap) in status.S.items():
            row = by[cid]
            self.assertEqual(row["status"], st, cid)
            self.assertTrue(row["implementation"], cid)
            self.assertTrue(row["owner"], cid)
            if st == "VERIFIED":
                self.assertTrue(tests, cid)
            else:
                self.assertTrue(gap, f"{cid} non-verified without a stated gap")
        self.assertNotIn("MISSING", {r["status"] for r in rtm["rows"] if r["id"] in status.S})

    def test_referenced_paths_exist(self):
        for cid, (st, impl, tests, gap) in status.S.items():
            for ref in impl + tests:
                path = ref.split("::")[0].split("#")[0].split(" ")[0]
                if path == "RELEASE_EVIDENCE.json":   # generated by tools/release_evidence.py
                    continue
                if "/" in path or path.endswith((".py", ".md", ".yaml", ".json", ".lock")):
                    self.assertTrue((ROOT / path).exists(), f"{cid}: {path}")


class Perf(unittest.TestCase):
    def test_baseline_reproducible_metadata(self):
        b = json.loads((ROOT / "perf/baseline.json").read_text())
        for k in ("inv70_version", "environment", "vm", "service_prod", "burst", "tenants", "warm_vs_cold"):
            self.assertIn(k, b)
        self.assertTrue(b["burst"]["recovered"])
        self.assertLess(b["warm_vs_cold"]["warm_hit"]["p50_us"], b["warm_vs_cold"]["cold_spawn"]["p50_us"])

    def test_gate_blocks_regressions_and_missing_baseline(self):
        b = json.loads((ROOT / "perf/baseline.json").read_text())
        self.assertEqual(bench.gate(b, b), [])
        self.assertEqual(bench.gate(b, None), ["baseline missing"])
        worse = json.loads(json.dumps(b))
        worse["vm"]["arith6"]["p50_us"] *= 2
        self.assertTrue(bench.gate(worse, b))
        other = json.loads(json.dumps(b))
        other["environment"]["machine"] = "riscv"
        self.assertTrue(bench.gate(b, other))


