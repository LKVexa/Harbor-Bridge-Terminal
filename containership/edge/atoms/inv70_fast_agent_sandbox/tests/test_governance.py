class Exceptions(unittest.TestCase):
    def test_register_well_formed(self):
        reg = yaml.safe_load((ROOT / "EXCEPTIONS.yaml").read_text())
        ids = set()
        for e in reg:
            for k in ("id", "type", "requirement", "reason", "owner", "opened", "expires", "status"):
                self.assertIn(k, e)
            self.assertIn(e["type"], {"waiver", "exception", "tech-debt", "deprecation"})
            self.assertNotIn(e["id"], ids)
            ids.add(e["id"])
            self.assertGreater(str(e["expires"]), str(e["opened"]))

    def test_every_blocked_item_has_register_entry(self):
        reg = yaml.safe_load((ROOT / "EXCEPTIONS.yaml").read_text())
        covered = {e["requirement"] for e in reg}
        for cid, (st, *_rest) in status.S.items():
            if st == "BLOCKED" and cid != "INV-70-C068":
                self.assertIn(cid, covered)


class Evidence(unittest.TestCase):
    def test_lock_checker_rejects_ranges_and_unset_hash(self):
        self.assertTrue(lock.problems("wasmtime>=25"))
        self.assertTrue(lock.problems("wasmtime==25.0.0 --hash=sha256:UNSET"))
        self.assertEqual(lock.problems("wasmtime==25.0.0 --hash=sha256:" + "a" * 64), [])

    def test_evidence_self_digest_detects_tamper(self):
        import hashlib
        ev = importlib.import_module(_path.PKG + ".tools.release_evidence")
        body = {"release": "x", "verdict": "NOT_ACCEPTED"}
        doc = dict(body, self_digest=hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest())
        self.assertTrue(ev.verify(doc))
        doc["verdict"] = "ACCEPTED"
        self.assertFalse(ev.verify(doc))
        p = ROOT / "RELEASE_EVIDENCE.json"
        if p.exists():
            self.assertTrue(ev.verify(json.loads(p.read_text())), "RELEASE_EVIDENCE.json was modified after generation")

